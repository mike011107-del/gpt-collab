def glyph_svg(strokes, x, y, size, sw=80, colour="#194764"):
    """把一個字畫在 (x, y) 起、邊長 size 的方格裡，sw 是 1000 格裡的筆寬。"""
    k = size / 1000.0
    out = []
    for s in strokes:
        pts = " ".join(f"{x + px * k:.1f},{y + py * k:.1f}" for px, py in s)
        out.append(
            f'<polyline points="{pts}" fill="none" stroke="{colour}" '
            f'stroke-width="{sw * k:.1f}" stroke-linecap="butt" stroke-linejoin="miter" stroke-miterlimit="2"/>'
        )
    return "\n".join(out)
